package org.example.models;

import org.example.exceptions.InvalidAmountException;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

public class AccountTest {

    @BeforeEach
    void resetCounters() {
        Account.resetCounter();
        Customer.resetCounter();
        Transaction.resetCounter();
    }

    /** Helper: build a checking account so overdraft/min-balance rules
     *  don't interfere with basic balance checks. */
    private Account newCheckingAccount(double balance) {
        return new CheckingAccount(
                new RegularCustomer("Test User", "+1-555-0000", "1 Test St", 30),
                balance, "Active");
    }

    @Test
    void depositUpdatesBalance() {
        Account acc = newCheckingAccount(1000);
        acc.deposit(500);
        assertEquals(1500.0, acc.getBalance(), 0.001);
    }

    @Test
    void depositNegativeAmountThrowsException() {
        Account acc = newCheckingAccount(1000);
        assertThrows(InvalidAmountException.class, () -> acc.deposit(-100));
        assertEquals(1000.0, acc.getBalance(), 0.001); // unchanged
    }

    @Test
    void depositZeroAmountThrowsException() {
        Account acc = newCheckingAccount(1000);
        assertThrows(InvalidAmountException.class, () -> acc.deposit(0));
        assertEquals(1000.0, acc.getBalance(), 0.001);
    }

    @Test
    void withdrawUpdatesBalance() {
        Account acc = newCheckingAccount(1000);
        acc.withdraw(200);
        assertEquals(800.0, acc.getBalance(), 0.001);
    }

    @Test
    void withdrawNegativeAmountThrowsException() {
        Account acc = newCheckingAccount(1000);
        assertThrows(InvalidAmountException.class, () -> acc.withdraw(-50));
        assertEquals(1000.0, acc.getBalance(), 0.001);
    }

    @Test
    void withdrawZeroAmountThrowsException() {
        Account acc = newCheckingAccount(1000);
        assertThrows(InvalidAmountException.class, () -> acc.withdraw(0));
        assertEquals(1000.0, acc.getBalance(), 0.001);
    }

    @Test
    void processTransactionDepositIncreasesBalance() {
        Account acc = newCheckingAccount(1000);
        acc.processTransaction(500, "DEPOSIT");
        assertEquals(1500.0, acc.getBalance(), 0.001);
    }

    @Test
    void processTransactionWithdrawalDecreasesBalance() {
        Account acc = newCheckingAccount(1000);
        acc.processTransaction(200, "WITHDRAWAL");
        assertEquals(800.0, acc.getBalance(), 0.001);
    }

    @Test
    void processTransactionUnknownTypeThrows() {
        Account acc = newCheckingAccount(1000);
        assertThrows(IllegalArgumentException.class,
                () -> acc.processTransaction(100, "TRANSFER"));
        assertEquals(1000.0, acc.getBalance(), 0.001);
    }

    @Test
    void processTransactionInvalidAmountThrows() {
        Account acc = newCheckingAccount(1000);
        assertThrows(InvalidAmountException.class,
                () -> acc.processTransaction(-5, "DEPOSIT"));
        assertEquals(1000.0, acc.getBalance(), 0.001);
    }

    @Test
    void accountNumberAutoGenerated() {
        Account first  = newCheckingAccount(1000);
        Account second = newCheckingAccount(1000);
        assertEquals("ACC001", first.getAccountNumber());
        assertEquals("ACC002", second.getAccountNumber());
    }

    @Test
    void getAccountTypeReturnsCorrectType() {
        Account savings = new SavingsAccount(
                new RegularCustomer("Saver", "+1-555-0001", "2 Test St", 28),
                1000, "Active");
        Account checking = newCheckingAccount(1000);

        assertEquals("Savings",  savings.getAccountType());
        assertEquals("Checking", checking.getAccountType());
    }
}